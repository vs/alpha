_WRITES = ("new", "change", "merge", "conflict")
_ORDER = ("new", "change", "merge", "conflict", "stale", "skipped")
REVIEW = ".claude/alpha/hooks/review.py"
_RENDER_TIMEOUT = 120.0  # seconds for the old kit to render the old answers
REVIEW_NOTE = "The reviewer will look at alpha's changes at the next Stop."
_NOTES = {
    "merge": " (your edits kept)",
    "conflict": " (your edits overlap alpha's change: merge by hand)",
    "stale": " (alpha no longer generates it: delete it if you don't need it)",
    "skipped": " (you deleted it: alpha's change to it is left out)",
}


@dataclass(frozen=True)
class UpdatePlan:
    changes: tuple[Change, ...]
    new_components: tuple[str, ...]
    groups: dict[str, str]
    manifest: dict[str, Any]
    answers: dict[str, Any]
    notes: tuple[str, ...] = ()  # what adopt's settings merge kept of the repo's
    copies: Mapping[str, Path] = field(default_factory=dict[str, Path])
    upgraded_from: str | None = None  # the kit version the project had


def _read(path: Path) -> str | None:
    if not path.is_file():
        return None
    return path.read_bytes().decode("utf-8")


_BY_HAND = "make the change by hand, and record it with the project's /decision skill."


def _not_kept(target: Path) -> GenerateError:
    return GenerateError(
        f"{target} was generated before alpha kept the answers it generated "
        "from, so alpha can't tell your edits from its own changes and can't "
        f"update it. Instead, {_BY_HAND}"
    )


def _not_loaded(target: Path, manifest: dict[str, Any], problem: Exception) -> str:
    raw: object = manifest.get("defaults")
    defaults = cast(dict[str, object], raw) if isinstance(raw, dict) else {}
    path, version = defaults.get("path"), manifest.get("kit_version")
    by = f"alpha {version}" if isinstance(version, str) else "a different alpha"
    run = (
        f" with the kit defaults in {path}. Run ALPHA_SOURCE={path} alpha update "
        f"{target} with that alpha"
        if isinstance(path, str)
        else f". Run alpha update {target} with that alpha"
    )
    return (
        f"The answers {target} was generated from don't load with this alpha "
        f"({problem}). It was generated by {by}{run}, or {_BY_HAND}"
    )


def _baseline(
    target: Path, manifest: dict[str, Any]
) -> tuple[Records, dict[str, date], int]:
    records = Records.from_json(manifest.get("records"))
    raw: object = manifest.get("added")
    if records is None or not isinstance(raw, dict):
        raise _not_kept(target)
    try:
        added = {
            str(name): date.fromisoformat(cast(str, day))
            for name, day in cast(dict[object, object], raw).items()
        }
        year = date.fromisoformat(cast(str, manifest.get("generated_at"))).year
    except (TypeError, ValueError):
        raise _not_kept(target) from None
    return records, added, year


def _load(target: Path) -> tuple[dict[str, Any], dict[str, Any]]:
    path = target / PROJECT_JSON
    if not path.is_file():
        raise GenerateError(
            f"{target} has no alpha answers, so alpha didn't generate or adopt "
            "it. To bring an existing repo under alpha, run /alpha:adopt in it."
        )
    try:
        data: object = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        raise GenerateError(
            f"Fix {PROJECT_JSON}: it can't be read as JSON ({e})."
        ) from None
    if not isinstance(data, dict):
        raise GenerateError(f"Fix {PROJECT_JSON}: it isn't a JSON object.")
    top = cast(dict[str, Any], data)
    manifest: object = top.get("manifest")
    if not isinstance(manifest, dict):
        raise GenerateError(
            f"{target} isn't generated yet. Finish the interview with "
            "/alpha:new-project."
        )
    manifest = cast(dict[str, Any], manifest)
    if not isinstance(manifest.get("applied"), dict):
        raise _not_kept(target)
    return top, manifest


def _check_history(applied: dict[str, Any], current: dict[str, Any]) -> None:
    for key in ("decisions", "overrides"):
        now: object = current.get(key, [])
        now_list = cast(list[object], now) if isinstance(now, list) else []
        for i, entry in enumerate(cast(list[object], applied.get(key, []))):
            if i >= len(now_list) or now_list[i] != entry:
                raise GenerateError(
                    f"{key}[{i}] changed since the project was generated. Decision "
                    "records are history: put it back as it was, and add a new "
                    "decision for the change instead."
                )


def _moves(
    target: Path, before: Answers, after: Answers, rendered: tuple[Rendered, Rendered]
) -> dict[str, tuple[str, str]]:
    was, now = rendered
    old = {c.name: c.path for c in before.components}
    moves: dict[str, tuple[str, str]] = {}
    for c in after.components:
        if c.name not in old or old[c.name] == c.path:
            continue
        moved = [
            path
            for path, name in now.component_of.items()
            if name == c.name
            and _moved_from(path, old[c.name], c.path) in was.component_of
        ]
        there = (
            all((target / p).is_file() for p in moved)
            if moved
            else (target / c.path).is_dir()
        )
        if not there:
            raise GenerateError(
                f"The {c.name} component moves from {old[c.name]} to {c.path}. "
                "alpha doesn't move app code: move its files yourself (git mv), "
                "commit, then run this again."
            )
        moves[c.name] = (old[c.name], c.path)
    return moves


def _moved_from(path: str, old: str, new: str) -> str:
    return (PurePosixPath(old) / PurePosixPath(path).relative_to(new)).as_posix()


def _written_as(path: str, after: Rendered, moves: dict[str, tuple[str, str]]) -> str:
    """Where alpha wrote `path` before: its old place when its component moved."""
    name = after.component_of.get(path)
    return _moved_from(path, *moves[name]) if name in moves else path


def _changes(
    target: Path,
    before: Mapping[str, str],
    after: Mapping[str, str],
    written_as: Callable[[str], str],
) -> list[Change]:
    """Each file three ways: what alpha wrote (`before`), the user's copy on
    disk, and what alpha writes now."""
    changes: list[Change] = []
    for path in sorted({*before, *after}):
        disk = _read(target / path)
        change = classify(path, before.get(written_as(path)), after.get(path), disk)
        if change is not None and (change.text is None or change.text != disk):
            changes.append(change)
    return changes


def _version(text: object) -> tuple[int, ...] | None:
    if not isinstance(text, str):
        return None
    try:
        return tuple(int(part) for part in text.split("."))
    except ValueError:
        return None


def _upgrade_from(target: Path, manifest: dict[str, Any]) -> str | None:
    """The older kit version that set the project up, or None for this kit's."""
    old: object = manifest.get("kit_version")
    was, now = _version(old), _version(VERSION)
    if was is None or now is None or was == now:
        return None
    if was > now:
        raise GenerateError(
            f"{target} was set up by alpha {old}, newer than this alpha "
            f"({VERSION}). Update alpha (claude plugin update alpha@alpha), then "
            f"run alpha update {target} again."
        )
    return cast(str, old)


def _kit_version(kit: Path) -> str | None:
    try:
        text = (kit / "src/alpha/__init__.py").read_text(encoding="utf-8")
    except OSError:
        return None
    found = re.search(r'^VERSION(?::\s*str)?\s*=\s*"([^"]+)"', text, re.MULTILINE)
    return found.group(1) if found else None


def _git_archive(repo: Path, ref: str, into: Path) -> bool:
    """Write the tree of `ref` in `repo` into the new folder `into`."""
    try:
        done = subprocess.run(
            ["git", "-C", str(repo), "archive", "--format=tar", ref],
            capture_output=True,
            timeout=_RENDER_TIMEOUT,
        )
    except (OSError, subprocess.TimeoutExpired):
        return False
    if done.returncode != 0:
        return False
    with tarfile.open(fileobj=io.BytesIO(done.stdout)) as tar:
        tar.extractall(into, filter="data")
    return True


@contextmanager
def _old_kit(
    manifest: dict[str, Any], plugin_root: Path, old: str
) -> Generator[Path | None]:
    """A folder holding kit `old`: the one the manifest names, the recorded
    commit of a checkout, the plugin cache's copy, or this checkout's tag."""
    raw: object = manifest.get("defaults")
    defaults = cast(dict[str, object], raw) if isinstance(raw, dict) else {}
    named = defaults.get("path")
    recorded = Path(named).expanduser() if isinstance(named, str) else None
    commit = defaults.get("commit")
    for kit in (recorded, plugin_root.parent / old):
        if kit is not None and _kit_version(kit) == old:
            yield kit
            return
    refs = [
        (recorded, commit) if recorded and isinstance(commit, str) else None,
        (plugin_root, f"v{old}"),
    ]
    with tempfile.TemporaryDirectory() as tmp:
        for i, (repo, ref) in enumerate(r for r in refs if r is not None):
            kit = Path(tmp, str(i))
            if _git_archive(repo, ref, kit) and _kit_version(kit) == old:
                yield kit
                return
        yield None


# Runs inside the old kit, so it uses only what every kit since 0.1.0 has:
# render_project, which took a registry from 0.2.0 on, and the copied files,
# named _copies before 0.2.0.
_RENDER_OLD = """
import inspect, json, os, sys
from datetime import date
from pathlib import Path
kit, target = Path(sys.argv[1]), Path(sys.argv[2])
today = date.fromisoformat(sys.argv[3])
sys.path.insert(0, str(kit / "src"))
from alpha import answers, defaults, generate
from alpha.records import Records
data = json.loads((target / ".claude/alpha/project.json").read_text(encoding="utf-8"))
manifest = data["manifest"]
applied = manifest["applied"]
source = defaults.locate_source(kit, os.environ, Path.home())
was = answers.parse_answers(
    applied, target, generated=True, former=answers.generated_components(applied)
)
extra = {}
if "registry" in inspect.signature(generate.render_project).parameters:
    from alpha.registry import load_registry
    extra["registry"] = load_registry(source)
texts = generate.render_project(
    target,
    was,
    defaults.load_defaults(source),
    date.fromisoformat(manifest["generated_at"]).year,
    today,
    Records.from_json(manifest["records"]),
    {name: date.fromisoformat(day) for name, day in manifest["added"].items()},
    **extra,
).texts
copies = getattr(generate, "copied_files", None) or generate._copies
texts.update({rel: src.read_text(encoding="utf-8") for rel, src in copies(kit).items()})
json.dump(texts, sys.stdout)
"""


def _old_kit_texts(
    target: Path, plugin_root: Path, manifest: dict[str, Any], old: str, today: date
) -> dict[str, str]:
    """Every file kit `old` writes from the answers it set the project up
    from, rendered by that kit itself: the base of a kit upgrade."""
    with _old_kit(manifest, plugin_root, old) as kit:
        if kit is None:
            raise GenerateError(
                f"alpha {old} set {target} up, and that kit isn't on this machine, "
                "so alpha can't tell its text from your edits. Put it at "
                f"{plugin_root.parent / old} (git clone --branch v{old} "
                f"https://github.com/vs/alpha {plugin_root.parent / old}), then "
                f"run alpha update {target} again."
            )
        render = [sys.executable, "-I", "-c", _RENDER_OLD, str(kit), str(target)]
        try:
            done = subprocess.run(
                [*render, today.isoformat()],
                capture_output=True,
                text=True,
                timeout=_RENDER_TIMEOUT,
                # Every kit reads its recipes and defaults from here.
                env={**os.environ, "ALPHA_SOURCE": str(kit)},
            )
        except (OSError, subprocess.TimeoutExpired) as e:
            done = e
    if not isinstance(done, subprocess.CompletedProcess) or done.returncode != 0:
        why = (
            done.stderr.strip().splitlines()[-1:]
            if isinstance(done, subprocess.CompletedProcess)
            else [str(done)]
        )
        raise GenerateError(
            f"alpha {old}'s kit couldn't render the answers it set {target} up "
            f"from ({' '.join(why)}), so alpha can't upgrade it. Instead, {_BY_HAND}"
        )
    return cast(dict[str, str], json.loads(done.stdout))


def _moved_lockfiles(
    target: Path, wrote: Mapping[str, str], after: Rendered
) -> tuple[str, ...]:
    """A note for each lockfile on disk that the components stop using, as
    when separate packages become one workspace: the package manager wrote
    it, so alpha leaves deleting it to the user."""
    old = tomllib.loads(wrote.get(PRINCIPLES_TOML, ""))
    used = {lock for c in after.principles["components"] for lock in c["lockfiles"]}
    setups = {
        lock: c["commands"]["setup"]
        for c in after.principles["components"]
        for lock in c["lockfiles"]
    }
    notes: list[str] = []
    for c in cast(list[dict[str, Any]], old.get("components", [])):
        now = next(
            (n for n in after.principles["components"] if n["name"] == c.get("name")),
            None,
        )
        for lock in cast(list[str], c.get("lockfiles", [])):
            if now is None or lock in used or not (target / lock).is_file():
                continue
            new = ", ".join(now["lockfiles"])
            notes.append(
                f"{'stale':<10}{lock} ({c['name']} now locks its dependencies in "
                f"{new}: delete this file and the build output beside it; "
                f"`{setups[now['lockfiles'][0]]}` writes {new})"
                if now["lockfiles"]
                else f"{'stale':<10}{lock} ({c['name']} has no lockfile any "
                "more: delete it)"
            )
    return tuple(notes)


def plan_update(
    target: Path, plugin_root: Path, source: Source, today: date
) -> UpdatePlan:
    """The changes that bring the project to its answers. When an older kit set
    it up, also to this kit, copied files included: each file then merges
    against what that kit wrote, rendered by that kit (spec §5a)."""
    top, manifest = _load(target)
    records, added, year = _baseline(target, manifest)
    if (target / UPDATE_STATE).exists():
        raise GenerateError(
            "An update is waiting to be committed. Merge any proposals in "
            f"{PROPOSALS}/, run alpha commit-update {target}, then run alpha "
            "update again."
        )
    applied = cast(dict[str, Any], manifest["applied"])
    defaults = load_defaults(source)
    # One registry for both renders, so kit changes cancel out.
    registry = load_registry(source)
    try:
        was = parse_answers(
            applied, target, generated=True, former=generated_components(applied)
        )
        before = render_project(
            target, was, defaults, year, today, records, added, registry=registry
        )
    except (AnswersError, GenerateError, ValueError, KeyError) as e:
        raise GenerateError(_not_loaded(target, manifest, e)) from None
    try:
        now = parse_answers(top, target)
    except AnswersError as e:
        area = area_of(e.where)
        if area:
            raise GenerateError(f"Revisit the {area} area: {e}") from None
        raise GenerateError(f"Fix {PROJECT_JSON}: {e}") from None
    _check_history(applied, top)
    new_records = record_paths(now, known=records, taken=taken_numbers(target))
    dates = {c.name: added.get(c.name, today) for c in now.components}
    after = render_project(
        target, now, defaults, year, today, new_records, dates, registry=registry
    )
    moves = _moves(target, was, now, (before, after))
    upgraded_from = _upgrade_from(target, manifest)
    copies = copied_files(plugin_root) if upgraded_from else {}
    wrote = (
        _old_kit_texts(target, plugin_root, manifest, upgraded_from, today)
        if upgraded_from
        else before.texts
    )
    texts = {**after.texts}
    texts.update({rel: src.read_text(encoding="utf-8") for rel, src in copies.items()})
    changes = _changes(
        target, wrote, texts, lambda path: _written_as(path, after, moves)
    )
    touched = [c.path for c in changes if c.kind in _WRITES]
    dirty = status_paths(target, *touched, command="update") if touched else []
    if dirty:
        raise GenerateError(
            f"Commit or stash your changes to {', '.join(dirty)} first: alpha "
            "merges its changes into the committed files."
        )
    old_names = {c.name for c in was.components}
    for c in now.components:
        if c.name in old_names or c.path == ".":
            continue
        theirs = status_paths(target, c.path, command="update")
        if theirs:
            raise GenerateError(
                f"Commit or move your files in {c.path}/ first "
                f"({', '.join(theirs[:5])}), then run alpha update {target} again."
            )
    return UpdatePlan(
        changes=tuple(changes),
        new_components=tuple(c.name for c in now.components if c.name not in old_names),
        groups={p: commit_group(p, after.component_of) for p in touched},
        manifest={
            **manifest,
            "applied": answers_snapshot(top),
            "records": new_records.to_json(),
            "added": {name: day.isoformat() for name, day in dates.items()},
            "updated_at": today.isoformat(),
            **(
                {"kit_version": VERSION, "defaults": source_info(source)}
                if upgraded_from
                else {}
            ),
        },
        answers=top,
        notes=_moved_lockfiles(target, wrote, after),
        copies=copies,
        upgraded_from=upgraded_from,
    )


def _review_hook(target: Path, *args: str) -> str | None:
    script = target / REVIEW
    if not script.is_file():
        return None
    try:
        done = subprocess.run(
            ["python3", str(script), *args],
            cwd=target,
            # The hook finds its project here before cwd: in a Claude Code
            # session that is the session's project, which may not be target.
            env={**os.environ, "CLAUDE_PROJECT_DIR": str(target)},
            capture_output=True,
            text=True,
        )
    except OSError:
        return None
    return done.stdout if done.returncode == 0 else None


def _review_snapshot(target: Path) -> str | None:
    return (_review_hook(target, "snapshot") or "").strip() or None


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="")


def apply_update(target: Path, plan: UpdatePlan) -> list[str]:
    before_tree = _review_snapshot(target)
    for c in plan.changes:
        if c.text is None:
            continue
        if c.kind == "conflict":
            _write(target / PROPOSALS / c.path, c.text)
        elif c.kind in _WRITES:
            _write(target / c.path, c.text)
        if c.kind == "new" and c.path in plan.copies:  # the git hook runs as is
            (target / c.path).chmod(plan.copies[c.path].stat().st_mode & 0o777)
    manifest = dict(plan.manifest)
    old: object = manifest.get("files")
    kept = list(cast(dict[str, object], old)) if isinstance(old, dict) else []
    rels = sorted({*kept, *(c.path for c in plan.changes)})
    manifest["files"] = file_hashes(target, [r for r in rels if (target / r).is_file()])
    write_json(target / PROJECT_JSON, {**plan.answers, "manifest": manifest})
    conflicts = {
        c.path: digest((target / c.path).read_bytes())
        for c in plan.changes
        if c.kind == "conflict"
    }
    after_tree = _review_snapshot(target)
    carried = (
        before_tree is not None
        and after_tree is not None
        and _review_hook(target, "absorb", before_tree, after_tree) is not None
    )
    state = target / UPDATE_STATE
    state.parent.mkdir(parents=True, exist_ok=True)
    write_json(
        state,
        {
            "before_tree": before_tree,
            "after_tree": after_tree,
            "groups": plan.groups,
            "new_components": list(plan.new_components),
            "conflicts": conflicts,
        },
    )
    return [] if carried else [REVIEW_NOTE]


def describe(plan: UpdatePlan, target: Path) -> str:
    count = sum(c.kind in _WRITES for c in plan.changes)
    if not plan.changes and not plan.new_components:
        return "alpha update: nothing to change"
    kit = f" (kit {plan.upgraded_from} to {VERSION})" if plan.upgraded_from else ""
    lines = [f"alpha update{kit}: {count} file{'' if count == 1 else 's'} to change"]
    for c in sorted(plan.changes, key=lambda c: (_ORDER.index(c.kind), c.path)):
        lines.append(f"  {c.kind:<10}{c.path}{_NOTES.get(c.kind, '')}")
    lines += [f"  {note}" for note in plan.notes]
    if plan.new_components:
        flags = " ".join(f"--component {n}" for n in plan.new_components)
        lines.append(
            f"New components: {', '.join(plan.new_components)}. Then run: "
            f"alpha bootstrap {target} {flags}"
        )
    return "\n".join(lines)


def plan_diff(plan: UpdatePlan, target: Path) -> str:
    out: list[str] = []
    for c in plan.changes:
        if c.kind not in ("new", "change", "merge") or c.text is None:
            continue
        disk = _read(target / c.path) or ""
        out += difflib.unified_diff(
            disk.splitlines(keepends=True),
            c.text.splitlines(keepends=True),
            f"a/{c.path}",
            f"b/{c.path}",
        )
    return "".join(out)
