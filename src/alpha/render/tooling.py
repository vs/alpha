"""Render the repository checks' toolchain: mise.toml and the tools' configs."""

from collections.abc import Sequence
from typing import Any

from alpha.recipes import check_commands, mutants_run
from alpha.registry import Registry
from alpha.repo_checks import BETTERLEAKS_CONFIG, TOOLCHAIN, RepoCheck
from alpha.toml_write import dumps

MISE = "mise.toml"
RUMDL = ".rumdl.toml"
TYPOS = "_typos.toml"
LYCHEE = "lychee.toml"
BETTERLEAKS = BETTERLEAKS_CONFIG
_REGEX_META = frozenset("\\.+*?()|[]{}^$")
_TYPOS_ONLY = ["CHANGELOG.md"]  # release notes quote commit text verbatim

_MISE_HEADER = """\
# Generated by alpha: the repository checks' tools and tasks.
# `mise run ci` runs {ci_runs}, `mise run check` adds
# each component's checks, `mise run scheduled` runs the weekly scans, and
# `mise run check:toolchain` looks for newer releases of the pinned tools.
# `mise run --continue-on-error <task>` reports every failing check, not
# only the first.
# Tasks don't install missing tools of your global mise config.
"""
_TYPOS_HEADER = """\
# Generated by alpha: typos settings. For a word the project spells that way
# on purpose, add it under [default.extend-words], e.g. `ser = "ser"`.
"""
_RUMDL_HEADER = """\
# Generated by alpha: rumdl settings. `rumdl fmt .` fixes most findings.
# MD013: alpha writes one line per paragraph or list item, so editing a
# sentence never means rewrapping its paragraph. Headings and code blocks keep
# the 80-column limit.
"""
_LYCHEE_HEADER = """\
# Generated by alpha: lychee settings. exclude_path holds regular expressions,
# searched for in each file's path.
"""

_BETTERLEAKS_HEADER = """\
# Generated by alpha: betterleaks settings. The default rules, minus the
# lockfiles. The secrets check scans only the files git doesn't ignore (local
# secrets belong in .env files). paths holds regular expressions, searched for
# in each file's path.
"""


# The mutation-testing gate needs a diff and the component's toolchain: it
# runs here when ALPHA_BASE names the base (e.g. `ALPHA_BASE=main mise run
# ci`), and in CI in the component's own job, not in the one that runs this.
_MUTANTS = (
    'if [ -z "${{ALPHA_BASE:-}}" ] || [ -n "${{CI:-}}" ]; then '
    'echo "alpha: mutants skipped (set ALPHA_BASE to the base branch to run '
    "them here; in CI the component's job runs them)\"; "
    "else {run}; fi"
)


def _escape(ch: str) -> str:
    return f"\\{ch}" if ch in _REGEX_META else ch


def _part(part: str) -> str:
    """One path segment of a glob as a regular expression."""
    return "".join(
        "[^/]*" if ch == "*" else "[^/]" if ch == "?" else _escape(ch) for ch in part
    )


def _glob_body(glob: str) -> str:
    """A glob as a regular expression up to its end (see glob_regex)."""
    # A leading "/" is the repository root only; lychee names the files it
    # walks from there "./<path>".
    anchored = glob.startswith("/")
    parts = glob.strip("/").split("/")
    out: list[str] = []
    for i, part in enumerate(parts):
        if part == "**":
            out.append("(?:.*/)?")
            continue
        out.append(_part(part) if i == len(parts) - 1 else f"{_part(part)}/")
    return (r"^(?:\./)?" if anchored else "(?:^|/)") + "".join(out)


def glob_regex(glob: str) -> str:
    """A .gitignore-style glob as a regular expression searched for in a path."""
    return _glob_body(glob) + ("/" if glob.endswith("/") else "(?:$|/)")


def secret_paths(lockfiles: list[str]) -> list[str]:
    """betterleaks' allowlist regexes for the lockfiles. Its re2 engine never
    matches through a `(?:$|/)` group, so each one ends at the file name."""
    return [f"{_glob_body(lock)}$" for lock in dict.fromkeys(lockfiles)]


def _mise(
    checks: list[RepoCheck],
    registry: Registry,
    components: Sequence[dict[str, Any]],
    ci: bool,
) -> str:
    tools: dict[str, str] = {}
    for check in checks:
        if check.tool is None:
            continue
        pin = registry.tool(check.tool).pin
        assert pin is not None  # repo_checks refuses a tool without one
        tools.setdefault(pin.mise, pin.version)
    tasks: dict[str, Any] = {f"check:{c.id}": {"run": c.command} for c in checks}
    for c in components:
        tasks[f"check:component:{c['name']}"] = {
            "dir": c["path"],
            "run": [command for _, command in check_commands(c["commands"])],
        }
    gated = [c for c in components if c.get("mutants")]
    last_member: dict[str, str] = {}
    for c in gated:
        name = f"check:mutants:{c['name']}"
        tasks[name] = {
            "dir": c["path"],
            "run": _MUTANTS.format(run=mutants_run('"$ALPHA_BASE"', c)),
        }
        if c.get("workspace"):
            # Members are mutated in place in one tree, with one output
            # folder: one run at a time, each after the member before it.
            if c["stack"] in last_member:
                tasks[name]["depends"] = [last_member[c["stack"]]]
            last_member[c["stack"]] = name
    tasks["ci"] = {
        "description": "Run the repository checks CI runs on a pull request"
        if ci
        else "Run the repository checks",
        "depends": [
            *(f"check:{c.id}" for c in checks if c.when in ("pr", "both")),
            *(f"check:mutants:{c['name']}" for c in gated),
        ],
    }
    tasks["scheduled"] = {
        "description": "Run the repository checks CI runs on a schedule"
        if ci
        else "Run the weekly scans",
        # The toolchain check fails almost weekly, so CI runs it on its own.
        "depends": [
            f"check:{c.id}"
            for c in checks
            if c.when in ("schedule", "both") and c.id != TOOLCHAIN
        ],
    }
    tasks["check"] = {
        "description": "Run the pull-request checks and every component's checks",
        "depends": ["ci", *(f"check:component:{c['name']}" for c in components)],
    }
    # A task otherwise installs every missing tool of the user's global config
    # first. Bootstrap and CI install the project's tools.
    settings = {"task": {"run_auto_install": False}}
    ci_runs = "what CI runs on a pull request" if ci else "the repository checks"
    return (
        _MISE_HEADER.format(ci_runs=ci_runs)
        + "\n"
        + dumps({"settings": settings, "tools": tools, "tasks": tasks})
    )


def render_tooling(
    checks: list[RepoCheck],
    registry: Registry,
    ignored: list[str],
    lockfiles: list[str],
    *,
    components: Sequence[dict[str, Any]],
    ci: bool,
) -> dict[str, str]:
    """mise.toml (tools, one task per check, ci/scheduled/check) and the configs
    of typos, rumdl and lychee, which skip what git ignores (`ignored`, the
    .gitignore lines) and the lockfiles, and of betterleaks, which skips the
    lockfiles.

    `components` are the principles file's, for the `check:component:*` tasks;
    `ci` says whether the project has CI, for the tasks' wording.
    """
    excludes = [g for g in ignored if not g.startswith("!")] + lockfiles
    skip = list(dict.fromkeys(excludes))
    return {
        MISE: _mise(checks, registry, components, ci),
        TYPOS: _TYPOS_HEADER
        + "\n"
        + dumps({"files": {"extend-exclude": [*skip, *_TYPOS_ONLY]}}),
        RUMDL: _RUMDL_HEADER
        + "\n"
        + dumps({"global": {"exclude": skip}, "MD013": {"paragraphs": False}}),
        LYCHEE: _LYCHEE_HEADER
        + "\n"
        + dumps({"exclude_path": [glob_regex(g) for g in skip]}),
        BETTERLEAKS: _BETTERLEAKS_HEADER
        + "\n"
        + dumps(
            {
                "extend": {"useDefault": True},
                "allowlists": [
                    {
                        "description": "Lockfiles",
                        "paths": secret_paths(lockfiles),
                    }
                ],
            }
        ),
    }
