"""Render the repository checks' toolchain: mise.toml and the tools' configs."""

from collections.abc import Collection, Sequence
from typing import Any

from alpha.recipes import check_commands
from alpha.registry import Registry
from alpha.repo_checks import BETTERLEAKS_CONFIG, RepoCheck
from alpha.toml_write import dumps

MISE = "mise.toml"
RUMDL = ".rumdl.toml"
TYPOS = "_typos.toml"
LYCHEE = "lychee.toml"
BETTERLEAKS = BETTERLEAKS_CONFIG
_REGEX_META = frozenset("\\.+*?()|[]{}^$")
_GLOB_META = frozenset("*?[]")
_TYPOS_ONLY = ["CHANGELOG.md"]  # release notes quote commit text verbatim

_MISE_HEADER = """\
# Generated by alpha: the repository checks' tools and tasks.
# `mise run ci` runs what CI runs on a pull request, `mise run check` adds
# each component's checks, and `mise run scheduled` runs the scheduled ones.
# Tasks don't install missing tools of your global mise config.
"""
_TYPOS_HEADER = """\
# Generated by alpha: typos settings. For a word the project spells that way
# on purpose, add it under [default.extend-words], e.g. `ser = "ser"`.
"""
_RUMDL_HEADER = """\
# Generated by alpha: rumdl settings. `rumdl fmt .` fixes most findings.
# MD013: alpha writes one line per paragraph or list item, so editing a
# sentence never means rewrapping its paragraph. Headings and code blocks keep
# the 80-column limit.
"""
_LYCHEE_HEADER = """\
# Generated by alpha: lychee settings. exclude_path holds regular expressions,
# searched for in each file's path.
"""

_BETTERLEAKS_HEADER = """\
# Generated by alpha: betterleaks settings. The default rules, minus the files
# git ignores (local secrets belong in .env files) and the lockfiles. paths
# holds regular expressions, searched for in each file's path.
"""


def _escape(ch: str) -> str:
    return f"\\{ch}" if ch in _REGEX_META else ch


def _part(part: str, kept: Collection[str] = ()) -> str:
    """One path segment of a glob as a regular expression. A segment `<stem>*`
    leaves out the names in `kept` that start with the stem (RE2, which
    lychee's and betterleaks' paths use, has no lookahead)."""
    stem = part[:-1]
    if part.endswith("*") and not set(stem) & _GLOB_META:
        rests = {name[len(stem) :] for name in kept if name.startswith(stem)}
        if rests:
            return "".join(_escape(ch) for ch in stem) + _except(rests)
    return "".join(
        "[^/]*" if ch == "*" else "[^/]" if ch == "?" else _escape(ch) for ch in part
    )


def _except(words: set[str]) -> str:
    """Any path segment text (no "/") except the given words."""
    heads = sorted({w[0] for w in words if w})
    alternatives = [] if "" in words else [""]
    alternatives += [
        _escape(h) + _except({w[1:] for w in words if w and w[0] == h}) for h in heads
    ]
    others = "".join(f"\\{h}" if h in "\\]^-" else h for h in heads)
    alternatives.append(f"[^/{others}][^/]*")
    return "(?:" + "|".join(alternatives) + ")"


def _glob_body(glob: str, kept: Collection[str] = ()) -> str:
    """A glob as a regular expression up to its end (see glob_regex)."""
    parts = glob.rstrip("/").split("/")
    out: list[str] = []
    for i, part in enumerate(parts):
        if part == "**":
            out.append("(?:.*/)?")
            continue
        last = i == len(parts) - 1
        text = _part(part, kept if last else ())
        out.append(text if last else f"{text}/")
    return "(?:^|/)" + "".join(out)


def glob_regex(glob: str) -> str:
    """A .gitignore-style glob as a regular expression searched for in a path."""
    return _glob_body(glob) + ("/" if glob.endswith("/") else "(?:$|/)")


def secret_paths(excludes: list[str]) -> list[str]:
    """betterleaks' allowlist regexes for the .gitignore-style `excludes`.

    Its re2 engine never matches through a `(?:$|/)` group, so a file glob
    becomes two regexes: the path ends there, or a folder does. A `!` entry
    naming a file (`!.env.example`) is cut out of the `<stem>*` globs, since
    git tracks it."""
    kept = [g[1:] for g in excludes if g.startswith("!") and "/" not in g[1:]]
    kept = [name for name in kept if not set(name) & _GLOB_META]
    out: list[str] = []
    for glob in dict.fromkeys(g for g in excludes if not g.startswith("!")):
        body = _glob_body(glob, kept)
        out += [f"{body}/"] if glob.endswith("/") else [f"{body}$", f"{body}/"]
    return out


def _mise(
    checks: list[RepoCheck],
    registry: Registry,
    components: Sequence[dict[str, Any]],
) -> str:
    tools: dict[str, str] = {}
    for check in checks:
        if check.tool is None:
            continue
        pin = registry.tool(check.tool).pin
        assert pin is not None  # repo_checks refuses a tool without one
        tools.setdefault(pin.mise, pin.version)
    tasks: dict[str, Any] = {f"check:{c.id}": {"run": c.command} for c in checks}
    for c in components:
        tasks[f"check:component:{c['name']}"] = {
            "dir": c["path"],
            "run": [command for _, command in check_commands(c["commands"])],
        }
    tasks["ci"] = {
        "description": "Run the repository checks CI runs on a pull request",
        "depends": [f"check:{c.id}" for c in checks if c.when in ("pr", "both")],
    }
    tasks["scheduled"] = {
        "description": "Run the repository checks CI runs on a schedule",
        "depends": [f"check:{c.id}" for c in checks if c.when in ("schedule", "both")],
    }
    tasks["check"] = {
        "description": "Run the pull-request checks and every component's checks",
        "depends": ["ci", *(f"check:component:{c['name']}" for c in components)],
    }
    # A task otherwise installs every missing tool of the user's global config
    # first. Bootstrap and CI install the project's tools.
    settings = {"task": {"run_auto_install": False}}
    return (
        _MISE_HEADER
        + "\n"
        + dumps({"settings": settings, "tools": tools, "tasks": tasks})
    )


def render_tooling(
    checks: list[RepoCheck],
    registry: Registry,
    excludes: list[str],
    *,
    components: Sequence[dict[str, Any]],
) -> dict[str, str]:
    """mise.toml (tools, one task per check, ci/scheduled/check) and the configs
    of typos, rumdl and lychee, which skip `excludes` (.gitignore-style globs).

    `components` are the principles file's, for the `check:component:*` tasks.
    """
    skip = list(dict.fromkeys(g for g in excludes if not g.startswith("!")))
    return {
        MISE: _mise(checks, registry, components),
        TYPOS: _TYPOS_HEADER
        + "\n"
        + dumps({"files": {"extend-exclude": [*skip, *_TYPOS_ONLY]}}),
        RUMDL: _RUMDL_HEADER
        + "\n"
        + dumps({"global": {"exclude": skip}, "MD013": {"paragraphs": False}}),
        LYCHEE: _LYCHEE_HEADER
        + "\n"
        + dumps({"exclude_path": [glob_regex(g) for g in skip]}),
        BETTERLEAKS: _BETTERLEAKS_HEADER
        + "\n"
        + dumps(
            {
                "extend": {"useDefault": True},
                "allowlists": [
                    {
                        "description": "Files git ignores, and lockfiles",
                        "paths": secret_paths(excludes),
                    }
                ],
            }
        ),
    }
