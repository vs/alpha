"""Render the project's CI workflow: each component's checks, as CLAUDE.md lists."""

import os
import re
from pathlib import Path
from typing import Any, cast

from alpha.defaults import locate_source
from alpha.recipes import RecipeBook, check_commands
from alpha.registry import BUNDLED, Registry, load_registry
from alpha.yaml_write import Commented, dumps

WORKFLOW = ".github/workflows/ci.yml"
DEPENDABOT = ".github/dependabot.yml"
_CHECKOUT = "actions/checkout"
_HEADER = "# Generated by alpha: each component's checks, as in CLAUDE.md.\n"
_DIR = re.compile(r"\$\{dir\}")


def _expand(value: object, folder: str) -> object:
    """Recipe step values with ${dir} replaced by the component folder."""
    if isinstance(value, str):
        return _DIR.sub(lambda _: folder, value)  # every other $ stays
    if isinstance(value, dict):
        items = cast("dict[str, object]", value).items()
        return {k: _expand(v, folder) for k, v in items}
    if isinstance(value, list):
        return [_expand(v, folder) for v in cast("list[object]", value)]
    return value


def _pinned(registry: Registry, repo: str) -> Commented:
    action = registry.action(repo)
    return Commented(f"{repo}@{action.sha}", action.version)


def _step(step: object, folder: str) -> object:
    """A recipe step: ${dir} expanded, its version shown as a comment on `uses`."""
    expanded = cast("dict[str, object]", _expand(step, folder))
    version = expanded.pop("version", None)
    if isinstance(version, str) and isinstance(expanded.get("uses"), str):
        expanded["uses"] = Commented(cast("str", expanded["uses"]), version)
    return expanded


def _job(
    component: dict[str, Any], book: RecipeBook, registry: Registry
) -> dict[str, object]:
    recipe = book.get(component["stack"])
    path = component["path"]
    folder = "" if path == "." else f"{path}/"
    job: dict[str, object] = {
        "runs-on": "ubuntu-latest",
        "defaults": {"run": {"working-directory": path}},
    }
    if recipe.ci.env:
        job["env"] = dict(recipe.ci.env)
    # The jobs only read the repository, so the token isn't left on disk.
    steps: list[object] = [
        {
            "uses": _pinned(registry, _CHECKOUT),
            "with": {"persist-credentials": False},
        }
    ]
    steps += [_step(step, folder) for step in recipe.ci.steps]
    steps += [
        {"name": step, "run": command}
        for step, command in check_commands(component["commands"])
    ]
    job["steps"] = steps
    return job


def render_ci(
    principles: dict[str, Any],
    ci: str,
    book: RecipeBook | None = None,
    registry: Registry | None = None,
) -> dict[str, str]:
    """The workflow file for the chosen CI provider; nothing for "none"."""
    if ci == "none":
        return {}
    recipes = book or RecipeBook()
    pins = registry or load_registry(locate_source(BUNDLED, os.environ, Path.home()))
    workflow = {
        "name": "CI",
        "on": {"push": {"branches": ["main"]}, "pull_request": {}},
        "permissions": {"contents": "read"},
        "jobs": {c["name"]: _job(c, recipes, pins) for c in principles["components"]},
    }
    return {WORKFLOW: _HEADER + dumps(workflow)}


def render_dependabot(
    principles: dict[str, Any],
    updates: str,
    schedule: str,
    ci: str,
    book: RecipeBook | None = None,
) -> dict[str, str]:
    """Dependabot updates per component, and for the CI actions; nothing if manual."""
    if updates != "dependabot":
        return {}
    interval = {"interval": schedule}
    book = book or RecipeBook()
    entries: list[object] = [
        {
            "package-ecosystem": ecosystem,
            "directory": "/" if c["path"] == "." else f"/{c['path']}",
            "schedule": interval,
        }
        for c in principles["components"]
        if (ecosystem := book.get(c["stack"]).dependabot)  # "": no updates
    ]
    if ci == "github-actions":
        entries.append(
            {
                "package-ecosystem": "github-actions",
                "directory": "/",
                "schedule": interval,
            }
        )
    header = "# Generated by alpha: dependency update pull requests.\n"
    return {DEPENDABOT: header + dumps({"version": 2, "updates": entries})}
