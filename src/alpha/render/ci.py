import re
from typing import Any, cast

from alpha.baseline import ratchet_command
from alpha.recipes import RecipeBook, check_commands
from alpha.registry import Registry, default_registry
from alpha.repo_checks import TOOLCHAIN
from alpha.yaml_write import Commented, dumps

WORKFLOW = ".github/workflows/ci.yml"
SCHEDULED = ".github/workflows/scheduled.yml"
DEPENDABOT = ".github/dependabot.yml"
JACTIONLINT = ".github/jactionlint.yaml"
REPO_JOB = "repo"  # the CI job of the repository checks, next to the components'
_CHECKOUT = "actions/checkout"
_MISE = "jdx/mise-action"
_TIMEOUT_MINUTES = 30
_CRON = "17 6 * * 1"  # Mondays, off the hour so runners aren't all busy at once
_TREE_STEP = {
    "name": "Checks left the tree unchanged",
    "run": 'git diff --exit-code && test -z "$(git status --porcelain)"',
}
_PULL_REQUEST = "github.event_name == 'pull_request'"
_PUSH = "github.event_name != 'pull_request'"
_HEADER = "# Generated by alpha: each component's checks, as in CLAUDE.md.\n"
_SCHEDULED_HEADER = "# Generated by alpha: the repository's weekly checks.\n"
_DIR = re.compile(r"\$\{dir\}")
# jactionlint skips its policy rules (pinning, timeouts) in a file whose first
# comment says a tool wrote it, as the headers above do. The project owns these
# files (alpha update merges its edits), so they get every rule.
_JACTIONLINT = """\
# Generated by alpha: jactionlint settings. alpha writes the workflows, but
# the project owns them, so they get the policy rules too (pinning, timeouts).
generated-files: report
"""


def expand(value: object, folder: str) -> object:
    if isinstance(value, str):
        return _DIR.sub(lambda _: folder, value)
    if isinstance(value, dict):
        items = cast("dict[str, object]", value).items()
        return {k: expand(v, folder) for k, v in items}
    if isinstance(value, list):
        return [expand(v, folder) for v in cast("list[object]", value)]
    return value


def _pinned(registry: Registry, repo: str) -> Commented:
    action = registry.action(repo)
    return Commented(f"{repo}@{action.sha}", action.version)


def _step(step: object, folder: str) -> object:
    """A recipe step: ${dir} expanded, its version shown as a comment on `uses`."""
    expanded = cast("dict[str, object]", expand(step, folder))
    version = expanded.pop("version", None)
    if isinstance(version, str) and isinstance(expanded.get("uses"), str):
        expanded["uses"] = Commented(cast("str", expanded["uses"]), version)
    return expanded


def _job(
    component: dict[str, Any],
    principles: dict[str, Any],
    book: RecipeBook,
    registry: Registry,
) -> dict[str, object]:
    recipe = book.get(component["stack"])
    path = component["path"]
    folder = "" if path == "." else f"{path}/"
    job: dict[str, object] = {
        "runs-on": "ubuntu-latest",
        "timeout-minutes": _TIMEOUT_MINUTES,
        "defaults": {"run": {"working-directory": path}},
    }
    if recipe.ci.env:
        job["env"] = dict(recipe.ci.env)
    testing = principles.get("testing", {})
    threshold = testing.get("diff_coverage", 0)
    gated = bool(recipe.coverage) and threshold > 0
    # The jobs only read the repository, so the token isn't left on disk.
    # diff-cover compares against the base branch, so it needs the history.
    steps: list[object] = [_checkout(registry, full_history=gated)]
    steps += [_step(step, folder) for step in recipe.ci.steps]
    for step, command in check_commands(component["commands"]):
        entry: dict[str, object] = {"name": step, "run": command}
        if gated and step == "test":
            entry["if"] = _PUSH
        steps.append(entry)
    if gated:
        diff_cover = registry.tool("diff-cover").pin
        assert diff_cover is not None  # the registry pins every tool it lists
        steps += [
            {
                "name": "test with coverage",
                "if": _PULL_REQUEST,
                "run": _coverage_run(component, principles, recipe.coverage),
            },
            {
                "name": "diff coverage",
                "if": _PULL_REQUEST,
                # The branch name goes through the environment: inline in the
                # script it could hold shell syntax (jactionlint refuses it).
                "env": {"BASE_REF": "${{ github.base_ref }}"},
                "run": (
                    f"pipx run diff-cover=={diff_cover.version} "
                    f"{recipe.coverage_report} "
                    '--compare-branch="origin/${BASE_REF}" '
                    f"--fail-under={threshold}"
                    + (" --branch-coverage" if testing.get("exhaustive") else "")
                ),
            },
        ]
    steps.append(dict(_TREE_STEP))
    job["steps"] = steps
    return job


def _coverage_run(
    component: dict[str, Any], principles: dict[str, Any], coverage: str
) -> str:
    """The coverage run, through the ratchet when the tests are baselined, so
    the legacy failures the baseline holds don't fail every pull request."""
    check = f"test:{component['name']}"
    baselined = {str(e.get("id")) for e in principles.get("baselines", [])}
    if check not in baselined:
        return coverage
    return ratchet_command(check, component["path"]) + " --coverage"


def _checkout(registry: Registry, *, full_history: bool) -> dict[str, object]:
    options: dict[str, object] = {"persist-credentials": False}
    if full_history:
        options = {"fetch-depth": 0, **options}
    return {"uses": _pinned(registry, _CHECKOUT), "with": options}


def _mise_steps(
    registry: Registry, task: str, env: dict[str, str] | None = None
) -> list[object]:
    """mise with the pinned tools installed, then the task. It runs every check
    even when one fails, so the log shows them all."""
    command = f"mise run --continue-on-error {task}"
    run: dict[str, object] = {"name": f"mise run {task}", "run": command}
    if env:
        run["env"] = env
    return [
        {
            "uses": _pinned(registry, _MISE),
            "with": {"install": True, "cache": True},
        },
        run,
    ]


def _repo_job(registry: Registry) -> dict[str, object]:
    env = {
        "ALPHA_BASE": (
            "${{ github.event_name == 'pull_request' && "
            "format('origin/{0}', github.base_ref) || '' }}"
        ),
        "PR_BODY": "${{ github.event.pull_request.body }}",
    }
    steps: list[object] = [_checkout(registry, full_history=True)]
    steps += _mise_steps(registry, "ci", env)
    steps.append(dict(_TREE_STEP))
    return {
        "runs-on": "ubuntu-latest",
        "timeout-minutes": _TIMEOUT_MINUTES,
        "steps": steps,
    }


def _scheduled_job(registry: Registry) -> dict[str, object]:
    steps: list[object] = [_checkout(registry, full_history=False)]
    steps += _mise_steps(registry, "scheduled")
    # Pinned tools fall behind almost weekly: after the scans, whatever they
    # found, so it never stops them.
    toolchain = f"mise run check:{TOOLCHAIN}"
    steps.append({"name": toolchain, "if": "${{ !cancelled() }}", "run": toolchain})
    steps.append(dict(_TREE_STEP))
    return {
        "runs-on": "ubuntu-latest",
        "timeout-minutes": _TIMEOUT_MINUTES,
        "steps": steps,
    }


def _concurrency(*, cancel: bool) -> dict[str, object]:
    return {
        "group": "${{ github.workflow }}-${{ github.ref }}",
        "cancel-in-progress": cancel,
    }


def render_ci(
    principles: dict[str, Any],
    ci: str,
    book: RecipeBook | None = None,
    registry: Registry | None = None,
) -> dict[str, str]:
    if ci == "none":
        return {}
    recipes = book or RecipeBook()
    pins = registry or default_registry()
    workflow = {
        "name": "CI",
        "on": {"push": {"branches": ["main"]}, "pull_request": {}},
        "concurrency": _concurrency(cancel=True),
        "permissions": {"contents": "read"},
        "jobs": {
            **{
                c["name"]: _job(c, principles, recipes, pins)
                for c in principles["components"]
            },
            REPO_JOB: _repo_job(pins),
        },
    }
    scheduled: dict[str, object] = {
        "name": "Scheduled",
        "on": {"schedule": [{"cron": _CRON}], "workflow_dispatch": {}},
        "concurrency": _concurrency(cancel=False),
        "permissions": {"contents": "read"},
        "jobs": {"scheduled": _scheduled_job(pins)},
    }
    return {
        WORKFLOW: _HEADER + dumps(workflow),
        SCHEDULED: _SCHEDULED_HEADER + dumps(scheduled),
        JACTIONLINT: _JACTIONLINT,
    }


def render_dependabot(
    principles: dict[str, Any],
    updates: str,
    schedule: str,
    ci: str,
    book: RecipeBook | None = None,
    cooldown_days: int = 0,
) -> dict[str, str]:
    if updates != "dependabot":
        return {}
    interval = {"interval": schedule}
    book = book or RecipeBook()
    cooldown = {"cooldown": {"default-days": cooldown_days}} if cooldown_days else {}
    entries: list[object] = [
        {
            "package-ecosystem": ecosystem,
            "directory": "/" if c["path"] == "." else f"/{c['path']}",
            "schedule": interval,
            **cooldown,
        }
        for c in principles["components"]
        if (ecosystem := book.get(c["stack"]).dependabot)
    ]
    if ci == "github-actions":
        entries.append(
            {
                "package-ecosystem": "github-actions",
                "directory": "/",
                "schedule": interval,
                **cooldown,
            }
        )
    header = "# Generated by alpha: dependency update pull requests.\n"
    return {DEPENDABOT: header + dumps({"version": 2, "updates": entries})}
