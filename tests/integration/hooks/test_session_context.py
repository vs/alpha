import json

import _common

from .conftest import Project

EXCEPTIONS = """# Contributing

## Exceptions

A check skipped or loosened in one place needs a row here.

| Path | Check | Reason |
|---|---|---|
| `api/legacy.py` | `lint:api` | Generated by the vendor's tool. |

## Branching

| Not | An exception |
"""


def test_context_points_at_the_specification_and_contributing(
    project: Project,
) -> None:
    text = _common.context_text(project.root, project.principles())
    assert text.startswith("alpha: what the product does is in docs/specification.md")
    assert "CONTRIBUTING.md" in text.splitlines()[0]
    assert "decision record" not in text


def test_exception_rows_come_only_from_the_exceptions_table(project: Project) -> None:
    project.write("CONTRIBUTING.md", EXCEPTIONS)
    rows = _common.exception_rows(project.root)
    assert rows == [
        _common.ExceptionRow(
            "api/legacy.py",
            "lint:api",
            "| `api/legacy.py` | `lint:api` | Generated by the vendor's tool. |",
        )
    ]
    text = _common.context_text(project.root, project.principles())
    assert "Exceptions in effect (CONTRIBUTING.md):\n| `api/legacy.py`" in text


def test_only_a_new_path_and_check_counts_as_newly_excepted() -> None:
    """Rewording an older row's reason doesn't reopen its baseline."""
    head = "## Exceptions\n\n| Path | Check | Reason |\n|---|---|---|\n"
    before = head + "| `api/a.py` | `lint:api` | Vendored. |\n"
    reworded = head + "| `api/a.py` | `lint:api` | Vendored code. |\n"
    assert not _common.newly_excepted(reworded, before, "lint:api")
    added = reworded + "| `api/b.py` | `lint:api` | Generated. |\n"
    assert _common.newly_excepted(added, before, "lint:api")
    assert not _common.newly_excepted(added, before, "typecheck:api")


def test_no_contributing_means_no_exceptions(project: Project) -> None:
    assert _common.exception_rows(project.root) == []


def test_overrides_in_effect_say_change_scope_and_reason(project: Project) -> None:
    lines = _common.overrides_in_effect(project.principles())
    assert len(lines) == 1
    assert lines[0].startswith("observability: loosen (component:api): ")
    text = _common.context_text(project.root, project.principles())
    assert "Principle overrides:" in text.splitlines()


def test_accepted_findings_come_from_commit_trailers(project: Project) -> None:
    project.write("a.txt", "a\n")
    project.git("add", "a.txt")
    project.git(
        "commit",
        "-q",
        "-m",
        "docs: Keep a\n\nAccepts: F-abc123 the input is trusted here",
    )
    project.git(
        "commit",
        "-q",
        "--allow-empty",
        "-m",
        "fix: Keep b\n\nAccepts: F-0a1b2c same cause as F-def456\n\n"
        "Co-Authored-By: T <t@example.com>",
    )
    project.git("commit", "-q", "--allow-empty", "-m", "chore: Mention F-fff000")
    assert _common.accepted_findings(project.root) == {"F-abc123", "F-0a1b2c"}


def test_session_start_always_injects_the_context(project: Project) -> None:
    project.git("config", "core.hooksPath", ".claude/alpha/githooks")
    out = project.run_hook("session_start.py", {"hook_event_name": "SessionStart"})
    text = json.loads(out.stdout)["hookSpecificOutput"]["additionalContext"]
    assert text.startswith("alpha: what the product does")


def test_subagent_start_injects_the_same_context(project: Project) -> None:
    out = project.run_hook(
        "subagent_start.py",
        {"hook_event_name": "SubagentStart", "agent_id": "a1", "agent_type": "x"},
    )
    data = json.loads(out.stdout)["hookSpecificOutput"]
    assert data["hookEventName"] == "SubagentStart"
    assert data["additionalContext"] == _common.context_text(
        project.root, project.principles()
    )


def test_subagent_start_is_silent_outside_alpha_projects(project: Project) -> None:
    (project.root / "docs" / "principles.toml").unlink()
    out = project.run_hook("subagent_start.py", {"hook_event_name": "SubagentStart"})
    assert out.returncode == 0 and out.stdout == ""


def test_context_steers_code_with_the_writing_principles(project: Project) -> None:
    text = _common.context_text(project.root, project.principles())
    head = "Write code by these principles (docs/principles.toml):\n"
    assert head in text
    section = text.split(head)[1]
    for title in (
        "Smallest complete change",
        "Scope before writing",
        "Fix bugs at the root",
        "Lean structure",
    ):
        assert f"- {title}: " in section
    assert "Never cut validation at trust boundaries" in section


def test_a_dropped_writing_principle_is_not_injected(project: Project) -> None:
    project.drop_principle("lean-structure")
    text = _common.context_text(project.root, project.principles())
    assert "- Lean structure: " not in text
    assert "- Smallest complete change: " in text
