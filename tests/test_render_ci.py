import copy
from pathlib import Path
from typing import Any

import yaml

from alpha.answers import load_answers
from alpha.cli import PLUGIN_ROOT
from alpha.defaults import Source, load_defaults
from alpha.principles import build_principles
from alpha.recipes import check_commands
from alpha.render.ci import WORKFLOW, render_ci

FIXTURE = Path(__file__).parent / "fixtures" / "answers_valid.json"
PRINCIPLES = build_principles(
    load_defaults(Source(PLUGIN_ROOT, True, "")), load_answers(FIXTURE), "0.1.0"
)


def workflow(principles: dict[str, Any]) -> dict[Any, Any]:
    return yaml.safe_load(render_ci(principles, "github-actions")[WORKFLOW])


def values(node: object) -> list[str]:
    if isinstance(node, dict):
        return [v for item in node.values() for v in values(item)]
    if isinstance(node, list):
        return [v for item in node for v in values(item)]
    return [node] if isinstance(node, str) else []


def test_one_job_per_component_running_its_checks():
    jobs = workflow(PRINCIPLES)["jobs"]
    assert list(jobs) == ["api", "web"]
    api = jobs["api"]
    assert api["runs-on"] == "ubuntu-latest"
    assert api["defaults"] == {"run": {"working-directory": "api"}}
    assert api["env"] == {"UV_LOCKED": "1"}
    assert api["steps"][0]["uses"].startswith("actions/checkout@v")
    runs = [s for s in api["steps"] if "run" in s]
    commands = PRINCIPLES["components"][0]["commands"]
    assert [(s["name"], s["run"]) for s in runs] == check_commands(commands)
    assert "env" not in jobs["web"]
    node = next(s for s in jobs["web"]["steps"] if "setup-node" in s["uses"])
    assert node["with"]["node-version-file"] == "web/.node-version"


def test_root_component_paths_have_no_prefix():
    principles = copy.deepcopy(PRINCIPLES)
    principles["components"] = principles["components"][1:]
    principles["components"][0]["path"] = "."
    job = workflow(principles)["jobs"]["web"]
    assert job["defaults"]["run"]["working-directory"] == "."
    found = values(job)
    assert not [v for v in found if "${dir}" in v or v.startswith("./")]
    assert "pnpm-lock.yaml" in found


def test_triggers_and_permissions():
    data = workflow(PRINCIPLES)
    assert data["name"] == "CI"
    assert data["on"] == {"push": {"branches": ["main"]}, "pull_request": {}}
    assert data["permissions"] == {"contents": "read"}
    assert render_ci(PRINCIPLES, "github-actions")[WORKFLOW].startswith(
        "# Generated by alpha"
    )


def test_no_ci_writes_nothing():
    assert render_ci(PRINCIPLES, "none") == {}
