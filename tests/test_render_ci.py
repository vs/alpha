import copy
import re
from pathlib import Path
from typing import Any

import yaml

from alpha.answers import load_answers
from alpha.cli import PLUGIN_ROOT
from alpha.defaults import Source, load_defaults
from alpha.principles import build_principles
from alpha.recipes import check_commands
from alpha.render.ci import DEPENDABOT, WORKFLOW, _expand, render_ci, render_dependabot

FIXTURE = Path(__file__).parent / "fixtures" / "answers_valid.json"
PRINCIPLES = build_principles(
    load_defaults(Source(PLUGIN_ROOT, True, "")), load_answers(FIXTURE), "0.1.0"
)


def workflow(principles: dict[str, Any]) -> dict[Any, Any]:
    return yaml.safe_load(render_ci(principles, "github-actions")[WORKFLOW])


def values(node: object) -> list[str]:
    if isinstance(node, dict):
        return [v for item in node.values() for v in values(item)]
    if isinstance(node, list):
        return [v for item in node for v in values(item)]
    return [node] if isinstance(node, str) else []


def test_workflow_actions_pinned():
    text = render_ci(PRINCIPLES, "github-actions")[WORKFLOW]
    lines = [ln for ln in text.splitlines() if "uses:" in ln]
    assert len(lines) >= 3
    for line in lines:
        assert re.search(r'@[0-9a-f]{40}" # v', line), line


def test_one_job_per_component_running_its_checks():
    jobs = workflow(PRINCIPLES)["jobs"]
    assert list(jobs) == ["api", "web"]
    api = jobs["api"]
    assert api["runs-on"] == "ubuntu-latest"
    assert api["defaults"] == {"run": {"working-directory": "api"}}
    assert api["env"] == {"UV_LOCKED": "1"}
    assert api["steps"][0]["uses"].startswith("actions/checkout@")
    runs = [s for s in api["steps"] if "run" in s]
    commands = PRINCIPLES["components"][0]["commands"]
    assert [(s["name"], s["run"]) for s in runs] == check_commands(commands)
    assert "env" not in jobs["web"]
    node = next(s for s in jobs["web"]["steps"] if "setup-node" in s["uses"])
    assert node["with"]["node-version-file"] == "web/.node-version"


def test_root_component_paths_have_no_prefix():
    principles = copy.deepcopy(PRINCIPLES)
    principles["components"] = principles["components"][1:]
    principles["components"][0]["path"] = "."
    job = workflow(principles)["jobs"]["web"]
    assert job["defaults"]["run"]["working-directory"] == "."
    found = values(job)
    assert not [v for v in found if "${dir}" in v or v.startswith("./")]
    assert "pnpm-lock.yaml" in found


def test_checkout_keeps_no_credentials():
    for job in workflow(PRINCIPLES)["jobs"].values():
        assert job["steps"][0]["with"] == {"persist-credentials": False}


def test_dir_expansion_leaves_other_dollars_alone():
    assert _expand("${dir}a $$ $HOME ${{ env.X }}", "api/") == (
        "api/a $$ $HOME ${{ env.X }}"
    )


def test_triggers_and_permissions():
    data = workflow(PRINCIPLES)
    assert data["name"] == "CI"
    assert data["on"] == {"push": {"branches": ["main"]}, "pull_request": {}}
    assert data["permissions"] == {"contents": "read"}
    assert render_ci(PRINCIPLES, "github-actions")[WORKFLOW].startswith(
        "# Generated by alpha"
    )


def test_no_ci_writes_nothing():
    assert render_ci(PRINCIPLES, "none") == {}


def dependabot(principles: dict[str, Any], ci: str = "github-actions") -> Any:
    return yaml.safe_load(
        render_dependabot(principles, "dependabot", "weekly", ci)[DEPENDABOT]
    )


def test_dependabot_per_component_and_for_actions():
    data = dependabot(PRINCIPLES)
    assert data["version"] == 2
    assert [(u["package-ecosystem"], u["directory"]) for u in data["updates"]] == [
        ("uv", "/api"),
        ("npm", "/web"),
        ("github-actions", "/"),
    ]
    assert all(u["schedule"] == {"interval": "weekly"} for u in data["updates"])
    assert render_dependabot(PRINCIPLES, "dependabot", "weekly", "github-actions")[
        DEPENDABOT
    ].startswith("# Generated by alpha")


def test_dependabot_root_component_directory_is_slash():
    principles = copy.deepcopy(PRINCIPLES)
    principles["components"] = principles["components"][:1]
    principles["components"][0]["path"] = "."
    data = dependabot(principles, ci="none")
    assert data["updates"] == [
        {
            "package-ecosystem": "uv",
            "directory": "/",
            "schedule": {"interval": "weekly"},
        }
    ]


def test_manual_updates_write_nothing():
    assert render_dependabot(PRINCIPLES, "manual", "weekly", "github-actions") == {}


def test_cooldown_on_every_entry():
    data = yaml.safe_load(
        render_dependabot(
            PRINCIPLES, "dependabot", "weekly", "github-actions", cooldown_days=7
        )[DEPENDABOT]
    )
    assert len(data["updates"]) == 3
    assert all(u["cooldown"] == {"default-days": 7} for u in data["updates"])


def test_cooldown_zero_omits():
    data = dependabot(PRINCIPLES)
    assert all("cooldown" not in u for u in data["updates"])
